# Grading System Program

marks = float(input("Enter your marks: "))

if marks >= 80:
    print("Grade: A+")

elif marks >= 70:
    print("Grade: A")

elif marks >= 60:
    print("Grade: A-")

elif marks >= 50:
    print("Grade: B")

elif marks >= 40:
    print("Grade: C")

else:
    print("Grade: F")